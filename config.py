"""
Конфигурация обучения для оптимизации adversarial LED-паттернов.
Все параметры эксперимента определяются здесь.
"""


class TrainingConfig:

    # =========================================================================
    # СЕТЬ
    # =========================================================================
    SERVER_HOST = '127.0.0.1'
    SERVER_PORT = 5000

    # =========================================================================
    # КАМЕРА ПК
    # =========================================================================
    PC_CAMERA_INDEX    = 0
    CAMERA_WARMUP_TIME = 2.0   # секунд

    # =========================================================================
    # YOLO
    # =========================================================================
    YOLO_MODEL          = 'yolov8n.pt'
    YOLO_CONF_THRESHOLD = 0.55
    TARGET_CLASS        = 0    # класс "человек" в COCO

    # =========================================================================
    # ДИОДЫ / ПРОСТРАНСТВО ДЕЙСТВИЙ
    # =========================================================================
    BOARD_H  = 16   # высота сетки диодов на одной плате
    BOARD_W  = 16   # ширина сетки диодов на одной плате
    N_BOARDS = 37   # количество плат
    # Итого диодов: BOARD_H * BOARD_W * N_BOARDS = 9472
    # Расположение — змейка: чётные строки слева направо, нечётные справа налево

    # Размер суперпикселя: одно RGB-значение покрывает SUPERPIXEL_SIZE×SUPERPIXEL_SIZE диодов.
    # Должен нацело делить BOARD_H и BOARD_W. Допустимые значения: 1, 2, 4, 8, 16.
    # Степень сжатия: 1→1x, 2→4x, 4→16x, 8→64x, 16→256x
    SUPERPIXEL_SIZE = 4

    MAX_BRIGHTNESS = 10   # максимальная яркость диода (0–255)

    # =========================================================================
    # СОСТОЯНИЕ (STATE)
    # Среднее и стандартное отклонение по каждому каналу двух RPi камер.
    # state_dim = 12  (3 канала × 2 статистики × 2 камеры)
    # =========================================================================
    IMAGE_SIZE = 64   # размер для ресайза перед вычислением статистик

    # =========================================================================
    # ШУМ ДЛЯ ИССЛЕДОВАНИЯ
    # =========================================================================
    # Шум добавляется к состоянию ДО подачи в актор (расширяет исследование)
    STATE_NOISE_STD  = 0.05
    # Шум добавляется к действию ПОСЛЕ выхода актора (мелкая пертурбация)
    ACTION_NOISE_STD = 0.02

    # =========================================================================
    # ФУНКЦИЯ НАГРАДЫ
    # reward = REWARD_A * (DETECTION_THRESHOLD - детекция)
    #        + REWARD_B * дисперсия_действия
    #        + REWARD_C * отличие_от_предыдущего_действия
    # =========================================================================
    DETECTION_THRESHOLD  = 0.9   # целевой порог детекции
    REWARD_A             = 1e1   # вес члена детекции
    REWARD_B             = 1e2   # вес члена дисперсии (стимулирует разнообразие)
    REWARD_C             = 1e1   # вес члена отличия от предыдущего (стимулирует изменение)
    DETECTION_AVG_FRAMES = 3     # количество кадров для усреднения уверенности детекции

    # =========================================================================
    # ГИПЕРПАРАМЕТРЫ SAC
    # =========================================================================
    GAMMA    = 0.99
    TAU      = 0.005
    ACTOR_LR  = 1e-4
    CRITIC_LR = 1e-4
    ALPHA_LR  = 1e-4

    HIDDEN_DIMS    = [256, 256]
    GRAD_CLIP_NORM = 1.0    # максимальная норма градиента (None — отключить)

    BATCH_SIZE      = 64
    BUFFER_SIZE     = 50_000
    LEARNING_STARTS = 10   # начать обучение после N шагов

    # =========================================================================
    # ПАРАМЕТРЫ ОБУЧЕНИЯ
    # =========================================================================
    NUM_EPISODES          = 5000
    MAX_STEPS_PER_EPISODE = 1
    DEVICE                = 'cuda'
    VERBOSE               = True

    # =========================================================================
    # СОХРАНЕНИЕ
    # =========================================================================
    MODELS_DIR         = './checkpoints'
    LOGS_DIR           = './logs'
    DATASET_DIR        = './dataset'
    SAVE_MODEL_EVERY   = 1000
    SAVE_DATASET       = False
    SAVE_VISUALIZATION = False

    # =========================================================================
    # ТАЙМАУТЫ СОКЕТОВ
    # =========================================================================
    SOCKET_TIMEOUT         = 10   # сек — ожидание изображений от RPi
    PATTERN_RENDER_TIMEOUT = 60   # сек — ожидание подтверждения отрисовки

    # =========================================================================
    # ВИЗУАЛИЗАЦИЯ
    # =========================================================================
    SHOW_YOLO_DETECTIONS = True
    SHOW_LED_PATTERN     = True
    SHOW_ENV_IMAGES      = True
    VISUALIZATION_DELAY  = 1   # мс; 1 = обновлять каждый кадр, 0 = ждать клавишу

    WINDOW_POSITIONS = {
        'YOLO Detection - Adversarial Jacket': (0,   0),
        'LED Pattern':                          (700, 0),
        'RPi Camera 1':                         (0,   550),
        'RPi Camera 2':                         (700, 550),
    }
